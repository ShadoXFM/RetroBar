<#
  Lists every monitor-adjustments.json tag in the source and writes
    docs/monitor-adjustments.md              the format, the fields and the tags (where each is declared)
    RetroBar/Utilities/KnownMonitorTags.cs   the same tags as a list, for the warnings about a tag the app does not know

  Run it from the repository root after adding or renaming a MonitorOffset.Tag:
    pwsh tools/Generate-MonitorTagDocs.ps1
#>
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$source = Join-Path $root 'RetroBar'

# a tag -> where it is declared, and the suffixes the converter that picks it adds
$suffixes = @{
    'mediaPlayingToMonitorTagConverter' = @('Playing')
    'cpuTempShownToMonitorTagConverter' = @('NoCpuTemp')
    'taskStateToMonitorTagConverter'    = @('Active')
    'trayAloneToMonitorTagConverter'    = @('Alone')
}
$tags = @{}
function Add-Tag([string]$name, [string]$file, [string[]]$variants = @()) {
    if (-not $tags.ContainsKey($name)) { $tags[$name] = @{ Files = [System.Collections.Generic.SortedSet[string]]::new(); Variants = [System.Collections.Generic.SortedSet[string]]::new() } }
    [void]$tags[$name].Files.Add($file)
    foreach ($v in $variants) { [void]$tags[$name].Variants.Add($v) }
}

$files = Get-ChildItem $source -Recurse -Include *.xaml, *.cs |
    Where-Object { $_.FullName -notmatch '\\(obj|bin)\\' -and $_.Name -ne 'KnownMonitorTags.cs' }

foreach ($file in $files) {
    $relative = $file.FullName.Substring($source.Length + 1).Replace('\', '/')
    $text = [System.IO.File]::ReadAllText($file.FullName)

    foreach ($m in [regex]::Matches($text, 'MonitorOffset\.Tag="([A-Za-z0-9_]+)"')) { Add-Tag $m.Groups[1].Value $relative }
    foreach ($m in [regex]::Matches($text, 'MonitorOffset\.SetTag\([^,]+,\s*"([A-Za-z0-9_]+)"\)')) { Add-Tag $m.Groups[1].Value $relative }
    foreach ($m in [regex]::Matches($text, 'SetMonitorTag\(\w+,\s*"(Task\w+)"\)')) { Add-Tag $m.Groups[1].Value $relative @('Active'); Add-Tag ($m.Groups[1].Value + 'Active') $relative }
    foreach ($m in [regex]::Matches($text, 'MonitorAdjustments\.Get\([^,]+,\s*"([A-Za-z0-9_]+)"\)')) { Add-Tag $m.Groups[1].Value $relative }
    foreach ($m in [regex]::Matches($text, '=>\s*"((?:Media|Tray|Weather)[A-Za-z0-9_]+)"')) { Add-Tag $m.Groups[1].Value $relative }
    foreach ($m in [regex]::Matches($text, 'CreateTransportButton\("(\w+)",\s*"(\w+)"')) { Add-Tag $m.Groups[1].Value $relative; Add-Tag $m.Groups[2].Value $relative }
    if ($text -match 'TaskStateToMonitorTagConverter TagConverter') {
        foreach ($m in [regex]::Matches($text, '\(\w+,\s*"(Task\w+)"\)')) { Add-Tag $m.Groups[1].Value $relative @('Active'); Add-Tag ($m.Groups[1].Value + 'Active') $relative }
    }

    # a tag that a converter makes up from a state: Converter={StaticResource name}, ConverterParameter=Base (or in a MultiBinding)
    foreach ($m in [regex]::Matches($text, 'Converter=(?:\{StaticResource\s+|")?\{?StaticResource\s+(\w+)\}?"?[^<>]*?ConverterParameter="?(\w+)"?')) {
        $converter = $m.Groups[1].Value
        if ($suffixes.ContainsKey($converter)) {
            $base = $m.Groups[2].Value
            Add-Tag $base $relative $suffixes[$converter]
            foreach ($suffix in $suffixes[$converter]) { Add-Tag ($base + $suffix) $relative }
        }
    }
}

# the fields, from MonitorOffsetValue
$valueLines = [System.IO.File]::ReadAllLines((Join-Path $source 'Utilities/MonitorOffsetValue.cs'))
$fields = @()
$doc = @()
foreach ($line in $valueLines) {
    $trim = $line.Trim()
    if ($trim.StartsWith('///')) { $doc += ($trim -replace '^///\s?', ''); continue }
    $m = [regex]::Match($trim, '^public ([\w\?]+) (\w+) \{ get; set; \}')
    if ($m.Success -and $doc.Count -gt 0 -and ($doc -join ' ') -notmatch 'A per-monitor visual adjustment') {
        $text = (($doc -join ' ') -replace '</?summary>', '' -replace '\s+', ' ' -replace 'e\.g\.', 'e_g_').Trim()
        $first = ($text -split '(?<=[a-z\)"]\.)\s', 2)[0] -replace 'e_g_', 'e.g.'
        $fields += [pscustomobject]@{ Name = $m.Groups[2].Value; Type = $m.Groups[1].Value; Doc = $first }
    }
    $doc = @()
}

$names = $tags.Keys | Sort-Object

# ---- the markdown
$md = New-Object System.Text.StringBuilder
[void]$md.AppendLine('# monitor-adjustments.json')
[void]$md.AppendLine()
[void]$md.AppendLine('*Generated by `tools/Generate-MonitorTagDocs.ps1` - do not edit by hand.*')
[void]$md.AppendLine()
[void]$md.AppendLine('Per-monitor tuning of the taskbar, kept in `%LOCALAPPDATA%\RetroBar\monitor-adjustments.json` and read again whenever it is saved.')
[void]$md.AppendLine('It is keyed by the monitor''s device name (`\\.\DISPLAY1`), then by a tag; a tag is on an element in the XAML (`utilities:MonitorOffset.Tag`).')
[void]$md.AppendLine()
[void]$md.AppendLine('```json')
[void]$md.AppendLine('{')
[void]$md.AppendLine('  "\\\\.\\DISPLAY1": {')
[void]$md.AppendLine('    "HeightAdjustment": 1.6,')
[void]$md.AppendLine('    "MediaTrackText": { "ScrollSpeed": 30, "ScrollPause": 2, "Y": 0 },')
[void]$md.AppendLine('    "MediaSeekTimeText": { "FontFamily": "Tahoma", "Bold": true, "X": 0, "Y": 0.8 }')
[void]$md.AppendLine('  }')
[void]$md.AppendLine('}')
[void]$md.AppendLine('```')
[void]$md.AppendLine()
[void]$md.AppendLine('Values are in DIPs (1 DIP is 1.25 pixels at 125% scale), so `0.8` is one pixel there.')
[void]$md.AppendLine('A monitor can also have `RowCount` (the number of taskbar rows), `HeightAdjustment` (DIPs added to the taskbar''s height) and `TabWidthAdjustment` (DIPs added to how much wider a tab is than it is tall, in the Windows 11 style).')
[void]$md.AppendLine()
[void]$md.AppendLine('## Fields of a tag')
[void]$md.AppendLine()
[void]$md.AppendLine('| Field | Type | |')
[void]$md.AppendLine('|---|---|---|')
foreach ($f in $fields) { [void]$md.AppendLine("| ``$($f.Name)`` | $($f.Type) | $($f.Doc -replace '\|', '/') |") }
[void]$md.AppendLine()
[void]$md.AppendLine('## Tags')
[void]$md.AppendLine()
[void]$md.AppendLine('A tag that is chosen by a state has variants: `Playing` (media is playing), `NoCpuTemp` (no CPU temperature shown), `Active` (the tab is the active window), `Alone` (nothing but the tray icons and the clock in the tray box).')
[void]$md.AppendLine()
[void]$md.AppendLine('| Tag | Declared in | State variants |')
[void]$md.AppendLine('|---|---|---|')
foreach ($name in $names) {
    $entry = $tags[$name]
    $variants = if ($entry.Variants.Count) { ($entry.Variants | ForEach-Object { "``$name$_``" }) -join ', ' } else { '' }
    [void]$md.AppendLine("| ``$name`` | $(($entry.Files | ForEach-Object { '`' + $_ + '`' }) -join ', ') | $variants |")
}
$docs = Join-Path $root 'docs'
New-Item -ItemType Directory -Force $docs | Out-Null
[System.IO.File]::WriteAllText((Join-Path $docs 'monitor-adjustments.md'), $md.ToString(), (New-Object System.Text.UTF8Encoding $false))

# ---- the list in code
$cs = New-Object System.Text.StringBuilder
[void]$cs.AppendLine('// <auto-generated> by tools/Generate-MonitorTagDocs.ps1 - do not edit by hand. </auto-generated>')
[void]$cs.AppendLine('using System;')
[void]$cs.AppendLine('using System.Collections.Generic;')
[void]$cs.AppendLine()
[void]$cs.AppendLine('namespace RetroBar.Utilities')
[void]$cs.AppendLine('{')
[void]$cs.AppendLine('    /// <summary>Every tag that an element of the app has in monitor-adjustments.json (and the variants a state picks).</summary>')
[void]$cs.AppendLine('    public static class KnownMonitorTags')
[void]$cs.AppendLine('    {')
[void]$cs.AppendLine('        public static readonly HashSet<string> Names = new(StringComparer.Ordinal)')
[void]$cs.AppendLine('        {')
$all = New-Object System.Collections.Generic.SortedSet[string]
foreach ($name in $names) {
    [void]$all.Add($name)
    foreach ($v in $tags[$name].Variants) { [void]$all.Add($name + $v) }
}
foreach ($n in $all) { [void]$cs.AppendLine("            `"$n`",") }
[void]$cs.AppendLine('        };')
[void]$cs.AppendLine('    }')
[void]$cs.AppendLine('}')
[System.IO.File]::WriteAllText((Join-Path $source 'Utilities/KnownMonitorTags.cs'), $cs.ToString(), (New-Object System.Text.UTF8Encoding $true))

Write-Host "$($all.Count) tags, $($fields.Count) fields -> docs/monitor-adjustments.md, RetroBar/Utilities/KnownMonitorTags.cs"
